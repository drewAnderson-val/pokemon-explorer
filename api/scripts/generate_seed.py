"""Writes migrations/0002_seed_pokemon.sql from src/data/pokemon.json.

Run once from api/: `uv run python -m scripts.generate_seed`. The output is
committed; a test fails if it no longer matches the JSON.
"""

import json
from pathlib import Path
from typing import Any

from app.db.migrate import MIGRATIONS_DIR

POKEMON_JSON = Path(__file__).parents[2] / "src" / "data" / "pokemon.json"
SEED_FILE = MIGRATIONS_DIR / "0002_seed_pokemon.sql"

COLUMNS = (
    "id, name, types, height, weight, hp, attack, defense, special_attack,"
    " special_defense, speed, description, image_url, generation, is_legendary"
)


def text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def row(p: dict[str, Any]) -> str:
    legendary = p.get("isLegendary")
    values = [
        str(p["id"]),
        text(p["name"]),
        "ARRAY[" + ", ".join(text(t) for t in p["types"]) + "]::text[]",
        # repr gives the shortest text that reads back as the same float.
        repr(float(p["height"])),
        repr(float(p["weight"])),
        str(p["hp"]),
        str(p["attack"]),
        str(p["defense"]),
        str(p["specialAttack"]),
        str(p["specialDefense"]),
        str(p["speed"]),
        text(p["description"]),
        text(p["imageUrl"]),
        str(p["generation"]),
        "NULL" if legendary is None else ("true" if legendary else "false"),
    ]
    return "(" + ", ".join(values) + ")"


def render(records: list[dict[str, Any]]) -> str:
    rows = ",\n".join(row(p) for p in sorted(records, key=lambda p: p["id"]))
    return (
        "-- Generated by api/scripts/generate_seed.py from src/data/pokemon.json. Don't edit.\n"
        f"INSERT INTO pokemon ({COLUMNS}) VALUES\n{rows};\n"
    )


def main() -> None:
    SEED_FILE.write_text(render(json.loads(POKEMON_JSON.read_text())))


if __name__ == "__main__":
    main()
